def _render_traffic_zones() -> str:
    lines = [
        "# Generated by WardNode. Do not edit manually.",
    ]
    for site in Site.query.order_by(Site.id).all():
        policy = ensure_site_traffic_policy(site)
        key = _traffic_key(policy)
        if policy.rate_limit_enabled:
            lines.append(
                f"limit_req_zone {key} zone=req_site_{site.id}:10m "
                f"rate={policy.requests_per_second}r/s;"
            )
        if policy.conn_limit_enabled:
            lines.append(f"limit_conn_zone {key} zone=conn_site_{site.id}:10m;")
    return "\n".join(lines) + "\n"


