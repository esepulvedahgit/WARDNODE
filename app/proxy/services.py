def _render_geoip_conf(db_path: str) -> str:
    db_filename = Path(db_path).name if db_path else "GeoLite2-Country.mmdb"
    container_db_path = f"/etc/nginx/geoip/{db_filename}"
    db_exists = Path(db_path).exists() if db_path else False

    sites = Site.query.order_by(Site.id).all()

    if db_exists:
        maps = "\n".join(
            f"map $geoip2_country_code $geo_blocked_site_{s.id} {{\n"
            f"    default 0;\n"
            f"    include /etc/nginx/generated/10-blocklist-site-{s.id}.map;\n"
            f"}}"
            for s in sites
        )
        return f"""# Generated by WardNode — GeoIP configuration. Do not edit manually.
geoip2 {container_db_path} {{
    auto_reload 24h;
    $geoip2_country_code default=XX country iso_code;
}}

{maps}
"""
    # DB not available — define per-site variables as constant 0 so server blocks compile.
    maps_fallback = "\n".join(
        f"geo $geo_blocked_site_{s.id} {{\n    default 0;\n}}"
        for s in sites
    )
    return f"""# Generated by WardNode — GeoIP unavailable (DB not found). Blocking disabled.
{maps_fallback}
"""


